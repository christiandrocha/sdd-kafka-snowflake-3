"""Build .claude/sdd/SDD_V3_PACKAGE.md: a read-only consolidated view of the SDD artifacts.

Usage:  python tools/build_sdd_package.py           # (re)write the package
        python tools/build_sdd_package.py --check   # exit 1 if the committed package is stale (CI)
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / ".claude/sdd/SDD_V3_PACKAGE.md"
FEATURES = ["COST_GOVERNANCE", "SCD2_RESTAURANTS"]
PHASES = ["DEFINE", "DESIGN", "BUILD_REPORT", "VALIDATION", "RETRO"]

PARTS = [
    ("Part 1 — Agent rules (`CLAUDE.md`)", "CLAUDE.md"),
    ("Part 2 — SDD lifecycle (`.claude/sdd/README.md`)", ".claude/sdd/README.md"),
    ("Part 3 — Constitution (`.claude/sdd/CONSTITUTION.md`)", ".claude/sdd/CONSTITUTION.md"),
    (
        "Part 4 — Index, ownership and 15-day plan (`.claude/sdd/_index.md`)",
        ".claude/sdd/_index.md",
    ),
]
# Feature artifacts are included as they come to exist, in lifecycle order.
for _feature in FEATURES:
    for _phase in PHASES:
        _path = f".claude/sdd/features/{_feature}/{_phase}_{_feature}.md"
        if (ROOT / _path).exists():
            PARTS.append((f"Part {len(PARTS) + 1} — {_phase}: {_feature}", _path))
TEMPLATES = ["BRAINSTORM", "DEFINE", "DESIGN", "BUILD_REPORT", "VALIDATION", "SHIPPED", "RETRO"]


def anchor(title):
    a = re.sub(r"[^\w\s-]", "", title.lower())
    return re.sub(r"\s", "-", a)


def demote(text, levels):
    out, fence = [], False
    for line in text.splitlines():
        if line.startswith("```"):
            fence = not fence
        if not fence and re.match(r"^#{1,5} ", line):
            line = "#" * levels + line
        out.append(line)
    return "\n".join(out)


def build():
    links = {}
    for title, path in PARTS:
        name = pathlib.Path(path).name
        links[f"(features/{pathlib.Path(path).parent.name}/{name})"] = f"(#{anchor(title)})"
        links[f"(./{name})"] = f"(#{anchor(title)})"
    doc = [
        "# sdd-kafka-snowflake-3 — Spec-Driven Development Package",
        "",
        "> Consolidated, read-only view of every SDD artifact of v3.",
        "> Generated by `tools/build_sdd_package.py`. "
        "The files in the repository are the source of truth;",
        "> regenerate this document instead of editing it.",
        "",
        "## Contents",
        "",
    ]
    doc += [f"- [{t}](#{anchor(t)})" for t, _ in PARTS]
    doc.append("- [Appendix — Templates](#appendix--templates)")
    doc += [f"  - [{k}](#template-{k.lower()})" for k in TEMPLATES]
    doc += ["", ""]
    for title, path in PARTS:
        text = (ROOT / path).read_text()
        for old, new in links.items():
            text = text.replace(old, new)
        doc += ["---", "", f"## {title}", "", demote(text, 2), ""]
    doc += ["---", "", "## Appendix — Templates", ""]
    for k in TEMPLATES:
        text = (ROOT / f".claude/sdd/templates/{k}_TEMPLATE.md").read_text()
        doc += [
            f"### Template: {k}",
            "",
            f"<details><summary>{k}_TEMPLATE.md</summary>",
            "",
            demote(text, 3),
            "",
            "</details>",
            "",
        ]
    return "\n".join(doc) + "\n"


if __name__ == "__main__":
    content = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != content:
            print("SDD package is stale: run python tools/build_sdd_package.py")
            sys.exit(1)
        print("SDD package is up to date.")
    else:
        OUT.write_text(content)
        print(f"Wrote {OUT.relative_to(ROOT)}")
